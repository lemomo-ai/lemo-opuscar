"""data/yagi_cma_track.csv (CMA best track via IBTrACS v04r01) -> track.js
Run: python3 styles/flow-field/demo/tools/make_trackjs.py"""
import csv, os, datetime as dt
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
t0 = dt.datetime(2024, 9, 1)
rows = []
for r in csv.DictReader(open(os.path.join(D, 'data/yagi_cma_track.csv'), encoding='utf-8')):
    t = dt.datetime.strptime(r['time_utc'], '%Y-%m-%d %H:%M'); b = dt.datetime.strptime(r['time_bjt'], '%Y-%m-%d %H:%M')
    tau = (t - t0).total_seconds() / 3600
    rows.append(f"  [{tau:g}, {float(r['lat'])}, {float(r['lon'])}, {int(r['pres_hpa'])}, {int(r['wind_ms'])}, '{r['grade_cn']}', '{b.month}-{b.day}-{b.hour:02d}']")
open(os.path.join(D, 'track.js'), 'w', encoding='utf-8').write(
    "// CMA best track of Typhoon Yagi (2411), from IBTrACS v04r01 (CMA columns, wind converted back to m/s). Generated by tools/make_trackjs.py.\n"
    "// [τ hours since 2024-09-01 00 UTC, lat, lon, central pressure hPa, 2-min max wind m/s, grade, Beijing time M-D-HH]\n"
    "export const TRACK = [\n" + ',\n'.join(rows) + "\n];\n")
print(len(rows), 'rows')
