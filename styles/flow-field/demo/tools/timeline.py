"""The film's one timeline -> timeline.js (page), voice/timeline.json (mixer), the subtitles ../flow-field.srt.
Run from anywhere: python3 tools/timeline.py   (needs out/voice/dur.json from core/tts/tts.py)

- ANCHORS map the film clock (52 s) to the story clock (49 s) that the chart's storm and camera keys use ("old" in the code).
  The page plays story time through a monotone cubic over these keys, so the narration gets room without
  any shot being rewritten; the flow clock is integrated in film time, so strokes keep their screen speed.
- LINES: where each narration line starts (film seconds). Captions run from the line's start to
  max(end + 0.6, start + 1.8), never into the next caption.
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); D = os.path.dirname(HERE)
DUR = 52.0
ANCHORS = [(0, 0), (4.9, 4.7), (8.9, 8.6), (12.2, 11.9), (14.2, 13.9), (19.0, 18.7), (20.15, 19.85), (22.9, 22.6),
           (23.75, 23.45), (29.3, 26.0), (32.5, 29.2), (36.9, 33.4), (39.5, 36.0), (43.6, 41.4), (46.9, 43.9),
           (48.0, 44.7), (49.5, 45.3), (52.0, 47.6)]
START = {'v01': 0.15, 'v02': 3.45, 'v03': 7.54, 'v04': 10.4, 'v04b': 16.1, 'v05': 24.05, 'v06': 31.9,
         'v07': 37.1, 'v08': 41.7, 'v09': 47.85}
lines = json.load(open(os.path.join(D, 'voice/lines.json')))
dur = json.load(open(os.path.join(D, 'out/voice/dur.json')))
cues = []
for i, l in enumerate(lines):
    t0 = START[l['id']]; d = dur[l['id']]
    nxt = START[lines[i + 1]['id']] if i + 1 < len(lines) else DUR
    t1 = max(t0 + d + 0.6, t0 + 1.8)
    assert t1 <= nxt + 1e-6, (l['id'], t1, nxt)
    cues.append(dict(id=l['id'], t0=round(t0, 3), t1=round(t1, 3), end=round(t0 + d, 3), zh=l['zh'], en=l.get('sub', l['text'])))
TL = dict(dur=DUR, anchors=ANCHORS, cues=cues)
open(os.path.join(D, 'timeline.js'), 'w').write('// generated by tools/timeline.py\nexport const TL = ' + json.dumps(TL, ensure_ascii=False) + ';\n')
json.dump(TL, open(os.path.join(D, 'voice/timeline.json'), 'w'), ensure_ascii=False, indent=1)
def ts(x):
    ms = int(round(x * 1000)); return '%02d:%02d:%02d,%03d' % (ms // 3600000, ms // 60000 % 60, ms // 1000 % 60, ms % 1000)
srt = ''.join(f"{k + 1}\n{ts(c['t0'])} --> {ts(c['t1'])}\n{c['zh']}\n{c['en']}\n\n" for k, c in enumerate(cues))
open(os.path.join(D, '..', 'flow-field.srt'), 'w').write(srt)
for c in cues: print(f"{c['id']:5s} {c['t0']:6.2f}–{c['t1']:6.2f} ({c['t1'] - c['t0']:.2f}s, voice {c['end'] - c['t0']:.2f}s)  {c['en']}")
print('shortest caption %.2f s' % min(c['t1'] - c['t0'] for c in cues))
